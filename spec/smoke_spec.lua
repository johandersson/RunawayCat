local LoveMock = require("spec.support.love_mock")

describe("LÖVE application harness", function()
    before_each(function()
        LoveMock.install()
        dofile("main.lua")
    end)

    it("registers every required LÖVE callback", function()
        assert.is_function(love.load)
        assert.is_function(love.update)
        assert.is_function(love.draw)
        assert.is_function(love.keypressed)
        assert.is_function(love.keyreleased)
        assert.is_function(love.mousepressed)
    end)

    it("loads, starts, updates, and draws without an error", function()
        assert.has_no.errors(love.load)
        assert.has_no.errors(function()
            love.keypressed("return")
            love.update(1 / 60)
            love.draw()
        end)
    end)
end)
